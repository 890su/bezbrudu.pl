"""Subset the two brand fonts to the glyphs the site actually needs.

Run after `npm run build` whenever texts gain new characters:
    python scripts/subset-fonts.py
Reads every built page in dist/ plus a fixed safety set (full Polish, Russian
and Ukrainian alphabets, digits, typographic punctuation), subsets the
fontsource variable woff2 files per script, and writes public/fonts/*.woff2
and src/styles/fonts.css with matching unicode-range values.
"""
import glob
import html
import io
import re
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'node_modules' / '@fontsource-variable'
OUT = ROOT / 'public' / 'fonts'
CSS = ROOT / 'src' / 'styles' / 'fonts.css'

SAFETY = (
    ''.join(chr(c) for c in range(0x20, 0x7F))
    + 'ąćęłńóśźżĄĆĘŁŃÓŚŹŻäöüÄÖÜ'
    + ''.join(chr(c) for c in range(0x410, 0x450)) + 'ёЁ'
    + 'ґҐєЄіІїЇʼ’'
    + '–—‘’“”„«»…×−²·•№€₴ '
)

FAMILIES = {
    'Unbounded Variable': 'unbounded',
    'Onest Variable': 'onest',
}
SCRIPTS = ['latin', 'latin-ext', 'cyrillic']


def site_text() -> str:
    chars = set(SAFETY)
    for f in glob.glob(str(ROOT / 'dist' / '**' / '*.html'), recursive=True):
        s = Path(f).read_text(encoding='utf-8')
        s = re.sub(r'<(script|style)\b[^>]*>.*?</\1>', ' ', s, flags=re.S)
        chars |= set(html.unescape(re.sub(r'<[^>]+>', ' ', s)))
        # Strings the scripts render later live in the JSON island.
        for m in re.findall(r'<script type="application/json" id="ui">(.*?)</script>', Path(f).read_text(encoding='utf-8'), re.S):
            chars |= set(m)
    return ''.join(sorted(c for c in chars if c.isprintable() or c == ' '))


def ranges(codepoints):
    cps = sorted(codepoints)
    out, start, prev = [], None, None
    for c in cps:
        if start is None:
            start = prev = c
        elif c == prev + 1:
            prev = c
        else:
            out.append((start, prev))
            start = prev = c
    if start is not None:
        out.append((start, prev))
    return ','.join(f'U+{a:04X}' if a == b else f'U+{a:04X}-{b:04X}' for a, b in out)


def main():
    text = site_text()
    OUT.mkdir(parents=True, exist_ok=True)
    faces, report = [], []
    for family, slug in FAMILIES.items():
        for script in SCRIPTS:
            src = SRC / slug / 'files' / f'{slug}-{script}-wght-normal.woff2'
            font = TTFont(src)
            cmap = set(font.getBestCmap())
            wanted = {ord(c) for c in text} & cmap
            if script != 'latin':
                # Latin covers ASCII; other scripts keep only what the latin file lacks.
                latin = set(TTFont(SRC / slug / 'files' / f'{slug}-latin-wght-normal.woff2').getBestCmap())
                wanted -= latin
            if not wanted:
                continue
            opts = subset.Options()
            opts.flavor = 'woff2'
            opts.layout_features = ['*']
            opts.name_IDs = ['*']
            opts.notdef_outline = True
            sub = subset.Subsetter(opts)
            sub.populate(unicodes=wanted)
            sub.subset(font)
            buf = io.BytesIO()
            font.flavor = 'woff2'
            font.save(buf)
            name = f'{slug}-{script}.woff2'
            (OUT / name).write_bytes(buf.getvalue())
            report.append(f'{name}: {len(wanted)} glyphs, {len(buf.getvalue()) // 1024} KB (was {src.stat().st_size // 1024} KB)')
            faces.append(
                '@font-face {\n'
                f"  font-family: '{family}';\n"
                '  font-style: normal;\n'
                '  font-display: swap;\n'
                '  font-weight: 100 900;\n'
                f"  src: url('/fonts/{name}') format('woff2-variations'), url('/fonts/{name}') format('woff2');\n"
                f'  unicode-range: {ranges(wanted)};\n'
                '}\n'
            )
    CSS.write_text('/* Generated by scripts/subset-fonts.py. Do not edit by hand. */\n' + '\n'.join(faces), encoding='utf-8')
    print('\n'.join(report))


if __name__ == '__main__':
    main()
